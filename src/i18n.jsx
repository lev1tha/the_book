const translations = { ru, ky };

const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem(LANG_KEY) || "ru");
  const switchLang = useCallback((l) => { setLang(l); localStorage.setItem(LANG_KEY, l); }, []);
  const t = useCallback((path) => {
    const keys = path.split(".");
    let v = translations[lang];
    for (const k of keys) v = v?.[k];
    return v ?? path;
  }, [lang]);
  return <I18nCtx.Provider value={{ lang, switchLang, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
